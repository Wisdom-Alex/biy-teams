	  //this script is used to select and highlight a header/footer link when the user is on that part of the site, creating the 'breadcrumb trail'
	  //breadcrumb.txt is a file in each folder that contains the id of the element that should be highlighted.

		
		<?php
		//the breadcrumb.txt file may or may not be in the same directory as the page the user is on. 
		//it may be one or two directories above.
			function findBreadCrumb(){
				if (file_exists("breadcrumb.txt")){ //if in same directory, use the one in this directory
					include('breadcrumb.txt');
				}
				else if(file_exists("../breadcrumb.txt")){ // else find one above
					include('../breadcrumb.txt');
				}
				else if(file_exists("../../breadcrumb.txt")){ // else find two above
					include('../../breadcrumb.txt');
				}
			}
		?>

	  //NOTE: the elements of the "kids nav bar" is on each page twice, once in header and once in footer. therefore unique ids cannot be assigned
	  //to them. Instead, they are given class names. 
	  if (document.getElementById("<?php findBreadCrumb();?>")){ //user is on a page that is reached by a footer link
		document.getElementById("<?php findBreadCrumb();?>").style.color="red"; 
	  }else{//the user is on a page that is reached by the "kids nav bar". TWO elements need to be highlighted in red.
		  document.getElementsByClassName("<?php findBreadCrumb();?>")[0].style.color="red";
		  document.getElementsByClassName("<?php findBreadCrumb();?>")[1].style.color="red";
	  }
